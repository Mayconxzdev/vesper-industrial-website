export function getProductTechnicalSpecs(productId) {
    let specs = TECHNICAL_SPECS[productId] || null;

    // Fallback para banheiro e churrasqueira singular/plural
    if (!specs && productId) {
        if (productId === 'exaustor-banheiro') specs = TECHNICAL_SPECS['exaustores-banheiro'];
        if (productId === 'exaustor-churrasqueira') specs = TECHNICAL_SPECS['exaustores-churrasqueira'];
        if (productId === 'exaustores-banheiro') specs = TECHNICAL_SPECS['exaustor-banheiro'];
        if (productId === 'exaustores-churrasqueira') specs = TECHNICAL_SPECS['exaustor-churrasqueira'];
    }

    // Fallback para locações: limpa prefixos 'loc-' e sufixos '-asp' se não achado diretamente
    if (!specs && productId && productId.startsWith('loc-')) {
        let cleanId = productId.replace('loc-', '').replace('-asp', '');
        if (cleanId === 'exaustor-ex') cleanId = 'exaustores-ex';
        specs = TECHNICAL_SPECS[cleanId] || null;
    }

    if (!specs) return null;

    try {
        const copy = JSON.parse(JSON.stringify(specs));
        if (copy.sourceLabel && String(copy.sourceLabel).includes('Site antigo')) {
            copy.sourceLabel = 'Especificações técnicas Vesper';
        }

        // Anexar tabela mecânica de centrífugos para subcategorias se necessário
        if (
            productId && 
            productId.startsWith('exaustores-centrifugos') && 
            productId !== 'exaustores-centrifugos-mini' && 
            productId !== 'exaustores-centrifugos-pp'
        ) {
            const baseSpecs = TECHNICAL_SPECS['exaustores-centrifugos'];
            if (baseSpecs && productId !== 'exaustores-centrifugos') {
                const mechanicalSection = baseSpecs.sections.find(s => s.title.includes('Tabela de Medidas'));
                if (mechanicalSection && !copy.sections.some(s => s.title.includes('Tabela de Medidas'))) {
                    copy.sections.push(mechanicalSection);
                    copy.hasMechanicalDrawings = true;
                }
            }
        }

        return copy;
    } catch {
        return specs;
    }
}

export function getTechnicalSearchText(productId) {
    const specs = getProductTechnicalSpecs(productId);
    if (!specs) return '';

    return specs.sections
        .flatMap((section) => [
            section.title,
            ...(section.columns || []),
            ...(section.items || []),
            ...(section.rows || []).flat(),
        ])
        .filter(Boolean)
        .join(' ');
}
